package com.nexus.music.ui

/**
 * PERF-46: разрешены ли «бесконечные» декоративные анимации (бегущая волна VK и т. п.). Раздаётся из NexusRoot:
 * выключено при «Экономии батареи» и «Меньше анимации» (в том числе системный масштаб анимации = 0). Когда выключено,
 * рисуется статичный кадр — вид сохраняется, но кадровый цикл не крутится.
 */
val LocalAmbientMotion = androidx.compose.runtime.compositionLocalOf { true }

/**
 * OPT-06: глобальный потолок частоты кадров фоновых анимаций (частицы, фон «Edit»).
 * 0 — авто (каждый кадр дисплея, как раньше), 60 или 30. Значение пишет NexusViewModel.applyLive.
 *
 * Реальная экономия — в том, что цикл кадров перед ожиданием vsync делает `delay`, то есть главный поток
 * не просыпается на каждом кадре 90/120 Гц дисплея. Дальше ждём ближайший vsync, поэтому фактическая частота
 * чуть ниже номинальной (≈ 27 вместо 30) — для фона это незаметно.
 */
object FrameCap {
    @Volatile var fps: Int = 0

    /** Сколько миллисекунд подождать перед очередным `withFrameNanos`; 0 — не ждать. */
    fun preDelayMs(): Long = when (fps) {
        30 -> 24L
        60 -> 6L   // имеет смысл только на дисплеях быстрее 60 Гц; на 60 Гц vsync сам не даст больше
        else -> 0L
    }
}
